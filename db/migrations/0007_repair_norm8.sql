-- Data repair for the M2 import: NORM-8 took the most recent entry's category even when that entry's colour mapped
-- to no category, which left every entry with that title uncategorised (e.g. 163 "shower" entries).
-- Re-derive the category from the most recent entry that has one — only for imported entries still untouched since
-- the import — and record that as the synced state, so nothing is pushed to or recoloured in Google.
create temp table norm8_repair on commit drop as
  select e.id, latest.category_id
    from time_entries e
    join (
      -- as the import would have decided: only entries still as imported
      select distinct on (title) title, category_id from time_entries
       where gcal_event_id is not null and deleted_at is null and category_id is not null
         and last_synced_hash is not distinct from app_hash
       order by title, starts_at desc
    ) latest using (title)
   where e.gcal_event_id is not null and e.deleted_at is null and e.category_id is null
     and e.last_synced_hash is not distinct from e.app_hash;

insert into backups (trigger, description, entries)
  select 'manual', 'Before repairing import categories (NORM-8)', coalesce(jsonb_agg(to_jsonb(e) - 'gcal_event'), '[]'::jsonb)
    from time_entries e where e.id in (select id from norm8_repair)
  having count(*) > 0;

update time_entries e set category_id = r.category_id from norm8_repair r where e.id = r.id;

-- app_hash was regenerated by the update above; mark only the repaired entries as in sync.
update time_entries e set last_synced_hash = e.app_hash, last_synced_category_id = e.category_id
  from norm8_repair r where e.id = r.id;
